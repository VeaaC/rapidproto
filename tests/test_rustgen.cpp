std::string gen(std::string src) {
    return rustgen::generate_common(test::parse_file_ok(std::move(src)));
}

// Parse + analyze a single self-contained schema in memory (filling field type resolution), then
// emit its arena module. No imports, so a one-file ResolvedFileSet is enough.
std::string gen_arena(std::string src) {
    FileNode file = test::parse_file_ok(std::move(src));
    file.filename = "t.proto";
    ResolvedFileSet set;
    set.file_index["t.proto"] = set.files.size();
    set.files.push_back(std::move(file));
    auto analyzed = analyze(set);
    REQUIRE(analyzed.is_ok());
    return rustgen::generate_arena(set.files.back());
}

bool has(const std::string& haystack, std::string_view needle) {
    return haystack.find(needle) != std::string::npos;
}

// A golden file's contents: the `common` tree followed by the `arena` tree (siblings), as the
// compile crate (rust/rustgen-golden) includes them under one module.
std::string golden_body(std::string src) {
    FileNode file = test::parse_file_ok(std::move(src));
    file.filename = "t.proto";
    ResolvedFileSet set;
    set.file_index["t.proto"] = set.files.size();
    set.files.push_back(std::move(file));
    auto analyzed = analyze(set);
    REQUIRE(analyzed.is_ok());
    const FileNode& f = set.files.back();
    return rustgen::generate_common(f) + "\n" + rustgen::generate_arena(f);
}

// Regenerate-and-compare one golden (compiled by rust/rustgen-golden). Regenerated by the standard
// golden flow -- `tests/regen_goldens.sh`, which sets RAPIDPROTO_REGEN_GOLDEN -- like every other
// golden; no bespoke knob.
// NOLINTNEXTLINE(bugprone-easily-swappable-parameters): golden name then its schema source
void check_golden(const std::string& name, std::string src) {
    const std::string body = golden_body(std::move(src));
    const std::string path = std::string(RAPIDPROTO_RUSTGEN_GOLDEN_DIR) + "/" + name + ".rs";

    if (std::getenv("RAPIDPROTO_REGEN_GOLDEN") != nullptr) {
        std::ofstream out(path, std::ios::binary | std::ios::trunc);
        REQUIRE(out.good());
        out << body;
        SUCCEED();
        return;
    }
    const std::ifstream in(path, std::ios::binary);
    INFO("missing golden " << path << "; regenerate with tests/regen_goldens.sh");
    REQUIRE(in.good());
    std::ostringstream buf;
    buf << in.rdbuf();
    CHECK(buf.str() == body);
}

