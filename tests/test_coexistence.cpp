// From ONE golden dir generated by ONE invocation with both models -- a consumer's actual shape,
// and the only one with a single shared common header (see regen_goldens.sh [4b/5]).
#include "coexist_golden/nestenum.rp.hpp"
#include "coexist_golden/nestenum.rp.stream.hpp"
#include "coexist_golden/rootenum.rp.hpp"
#include "coexist_golden/rootenum.rp.stream.hpp"
#include "coexist_golden/rootnames.rp.hpp"
#include "coexist_golden/rootnames.rp.stream.hpp"
