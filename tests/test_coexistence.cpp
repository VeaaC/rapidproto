// The one TU in the suite that holds BOTH models of the same schemas at once.
//
// That is the whole point of it. Every collision the per-model roots exist to close needs both
// headers present to be observable: with the models at `<pkg>::stream`, a top-level `message
// stream` made the arena class and the streaming namespace the same name, and a package like
// `sib.stream.logging.v1` landed on the parent package's streaming types. A test file that includes
// one model's goldens -- which is every other test file -- compiles happily through all of it.
//
// So the INCLUDES below are the test. The assertions only add what a compile cannot say by itself:
// that the two models' types are distinct, and that an enum is one shared type across them.

